import tokensJson from '../tokens.json';

export const tokens = tokensJson;
export type Tokens = typeof tokens;

export type ThemeName = 'dark' | 'light';
export type ThemeColors = (typeof tokens)['color']['dark'];
export type StatusColors = (typeof tokens)['color']['status'];

export const statusColors = tokens.color.status;
export const breakpoints = tokens.layout.breakpoints;
export const motion = tokens.motion;
export const radius = tokens.radius;
export const spacing = tokens.spacing;
export const typography = tokens.typography;

/** Raw token name -> CSS custom property (e.g. bg0 -> --bg-0). */
function cssVarName(key: string): string {
  return `--${key.replace(/([A-Z])/g, '-$1').toLowerCase()}`;
}

function themeBlock(theme: ThemeName, selector: string): string {
  const colors = tokens.color[theme];
  const status = tokens.color.status;
  const lines = [
    ...Object.entries(colors).map(([key, value]) => `  ${cssVarName(key)}: ${value};`),
    `  --win: ${status.win[theme]};`,
    `  --loss: ${status.loss[theme]};`,
    `  --dispute: ${status.dispute[theme]};`,
  ];
  return `${selector} {\n${lines.join('\n')}\n}`;
}

/**
 * Emits the CSS variable block from the doc (Design System §12) plus status and radius tokens.
 * Consumed by `scripts/emit-css.mjs` to generate the web theme file.
 */
export function tokensToCss(): string {
  return [
    `/* AUTOGENERATED from packages/tokens/tokens.json — do not edit by hand. */`,
    themeBlock('dark', `:root, [data-theme='dark']`),
    themeBlock('light', `[data-theme='light']`),
    `:root {\n  --radius: ${tokens.radius.card}px;\n  --radius-control: ${tokens.radius.control}px;\n  --radius-modal: ${tokens.radius.modal}px;\n  --motion-micro: ${tokens.motion.durationMs.micro}ms;\n  --motion-default: ${tokens.motion.durationMs.default}ms;\n  --motion-sheet: ${tokens.motion.durationMs.sheet}ms;\n  --ease-standard: ${tokens.motion.easing};\n}`,
  ].join('\n\n');
}
